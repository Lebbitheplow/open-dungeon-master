#!/usr/bin/env node
// Writes src/lib/classes/feature-names.json: the genre classes' feature
// tables from the six src/lib/classes/*-features.json catalogs with the names
// only, which is all the grant tables (src/lib/srd/features.ts) and every
// page's first load need. The one-line rules text beside each name stays in
// the catalogs, fetched when a sheet asks for it (src/lib/classes/
// feature-text.ts), so a table no longer carries all six genres' text before
// its first paint (issue 411).
//
//   node scripts/build-feature-names.mjs           write the file
//   node scripts/build-feature-names.mjs --check   exit 1 when it is stale
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

// The catalogs in the order src/lib/classes/index.ts always read them.
export const GENRE_FILES = ["cyberpunk", "dark-fantasy", "horror", "mystery", "post-apocalyptic", "steampunk"];

const classesDir = path.join(path.dirname(fileURLToPath(import.meta.url)), "..", "src", "lib", "classes");
const out = path.join(classesDir, "feature-names.json");

const names = (levels) =>
  Object.fromEntries(Object.entries(levels).map(([level, features]) => [level, features.map((feature) => feature.n)]));

export function featureNames() {
  const classes = {};
  for (const file of GENRE_FILES) {
    const catalog = JSON.parse(fs.readFileSync(path.join(classesDir, `${file}-features.json`), "utf8"));
    for (const [classId, table] of Object.entries(catalog.classes)) {
      classes[classId] = {
        file,
        subclassLevel: table.subclassLevel,
        levels: names(table.levels),
        subclass: { name: table.subclass.name, levels: names(table.subclass.levels) },
      };
    }
  }
  return {
    _note:
      "GENERATED by scripts/build-feature-names.mjs from the *-features.json catalogs: the feature names only, for the grant tables and the first load. The rules text stays in the catalogs (src/lib/classes/feature-text.ts). Do not edit by hand; edit the catalog and re-run the script.",
    classes,
  };
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const text = `${JSON.stringify(featureNames(), null, 2)}\n`;
  if (process.argv.includes("--check")) {
    // A Windows checkout may hand the file back with CRLF line ends.
    const current = fs.existsSync(out) ? fs.readFileSync(out, "utf8").replace(/\r\n/g, "\n") : "";
    if (current !== text) {
      console.error("src/lib/classes/feature-names.json is stale: run node scripts/build-feature-names.mjs");
      process.exit(1);
    }
    console.log("feature-names.json is current");
  } else {
    fs.writeFileSync(out, text);
    console.log(`wrote ${path.relative(process.cwd(), out)}`);
  }
}
