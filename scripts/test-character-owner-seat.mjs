import assert from "node:assert/strict";
import { heroInput, openWorld } from "./lib/enforce-world.mjs";
const world=await openWorld({gameSettings:{multiCharacter:"all_active"}});
const ownerHero=world.addHero({name:"Owner"});
const playerHero=world.addHero({name:"Player"});
const route=await world.route("campaigns/[campaignId]/sheet");
const input=heroInput({name:"Second hero",abilities:{str:16,dex:15,con:14,int:13,wis:11,cha:9},proficiencies:{saves:["str","con"],skills:["Athletics","Perception"],languages:["Common","Elvish"],tools:[],armor:[],weapons:[]},portrait:{url:"/uploads/existing.webp"}});
const post=body=>route.POST(new Request("http://localhost/api/sheet",{method:"POST",headers:{"Content-Type":"application/json"},body:JSON.stringify(body)}),{params:Promise.resolve({campaignId:world.campaignId})});
world.signIn({id:playerHero.userId});
assert.equal((await post({...input,playerUserId:ownerHero.userId})).status,403);
world.signIn(world.owner);
assert.equal((await post({...input,playerUserId:"not-a-member"})).status,404);
assert.equal((await post({...input,playerUserId:playerHero.userId,libraryCharacterId:"private-library"})).status,403);
const response=await post({...input,playerUserId:playerHero.userId});
const result=await response.json();
assert.equal(response.status,201,JSON.stringify(result));
assert.equal(result.sheet.userId,playerHero.userId);
assert.equal(result.sheet.isCompanion,false);
const {getCharacterForUser}=await import("../src/lib/db/characters.ts");
assert.ok(getCharacterForUser(playerHero.userId,result.sheet.libraryCharacterId));
assert.equal(getCharacterForUser(world.owner.id,result.sheet.libraryCharacterId),null);
assert.equal(world.sheets().filter(x=>x.userId===world.owner.id).length,1);
console.log("ok: owner creates directly for a member; library, control and selection belong to that member");
console.log("ok: ordinary players, outsiders and private-library access are refused");
const {createHomebrew,homebrewRaceLabel}=await import("../src/lib/db/homebrew.ts");
const {patchSheet}=await import("../src/lib/db/sheets.ts");
const species=createHomebrew(world.owner.id,{kind:"race",name:"Table Species",data:{desc:"A table-defined species."}});
const raceId=`homebrew:${species.id}`;
const labeled=patchSheet(result.sheet.id,{race:raceId});
assert.equal(labeled.race,raceId);
assert.equal(labeled.raceLabel,"Table Species");
assert.equal(homebrewRaceLabel(playerHero.userId,raceId),undefined);
const privateSpecies=createHomebrew(playerHero.userId,{kind:"race",name:"Private Species",data:{desc:"Private."}});
assert.equal(homebrewRaceLabel(world.owner.id,`homebrew:${privateSpecies.id}`,world.campaignId),undefined);
const wrongKind=createHomebrew(world.owner.id,{kind:"feat",name:"Not a species",data:{desc:"A feat."}});
assert.equal(homebrewRaceLabel(playerHero.userId,`homebrew:${wrongKind.id}`,world.campaignId),undefined);
console.log("ok: Workshop species display their names while admitted IDs and author boundaries stay intact");
world.close();
