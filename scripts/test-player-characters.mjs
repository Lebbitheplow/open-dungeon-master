import assert from "node:assert/strict";
import { openWorld } from "./lib/enforce-world.mjs";
const world = await openWorld({ gameSettings: { multiCharacter: "all_active", mapsEnabled: true } });
const { ownedCharacters, selectedCharacter, initiativeCharacter, resolveActionCharacter } = await import("../src/lib/player-characters.ts");
const campaigns = await import("../src/lib/db/campaigns.ts");
const sheets = await import("../src/lib/db/sheets.ts");
const { createCompanionUser } = await import("../src/lib/db/users.ts");
const { buildPlayerMapView } = await import("../src/lib/battlemap/view.ts");
const { listRecentMessages } = await import("../src/lib/db/messages.ts");
const { characterAwaitingPlayer } = await import("../src/lib/dm/player-word.ts");
const a1 = world.addHero({ name: "A1" });
const a2 = world.addHero({ name: "A2", user: world.owner });
const b1 = world.addHero({ name: "B1" });
const b2 = world.addHero({ name: "B2", user: { id: b1.userId } });
const bot = createCompanionUser("Guide");
const companionSheet = sheets.createSheet(world.campaignId, bot.id, 1, { ...a1, name: "Guide" });
const companion = sheets.markSheetAsCompanion(companionSheet.id, "party", "Steady and helpful.");
assert.equal(companion.isCompanion, true);
const all = () => world.sheets();
assert.equal(ownedCharacters(all(), a1.userId).length, 2);
assert.equal(selectedCharacter(all(), a1.userId, a2.id).id, a2.id);
assert.equal(selectedCharacter(all(), a1.userId, b1.id).id, a1.id);
assert.equal(initiativeCharacter(all(), a1.userId, companion.id), null);
assert.equal(resolveActionCharacter({ sheets: all(), userId: a1.userId, characterId: b2.id, multiCharacter: "all_active" }).status, 404);
assert.equal(resolveActionCharacter({ sheets: all(), userId: a1.userId, selectedId: a2.id, initiativeId: a1.id, multiCharacter: "all_active" }).sheet.id, a1.id);
assert.equal(resolveActionCharacter({ sheets: all(), userId: a1.userId, characterId: a2.id, initiativeId: a1.id, multiCharacter: "all_active" }).status, 409);
assert.equal(resolveActionCharacter({ sheets: all(), userId: a1.userId, selectedId: a1.id, characterId: a2.id, multiCharacter: "off" }).status, 409);
assert.equal(resolveActionCharacter({ sheets: all(), userId: a1.userId, selectedId: a1.id, characterId: a2.id, initiativeId: b1.id, reaction: true, multiCharacter: "all_active" }).sheet.id, a2.id);
const { fieldedSheets } = await import("../src/lib/dm/roster.ts");
campaigns.updateGameSettings(world.campaignId, { multiCharacter: "one_active" });
campaigns.setMemberActiveCharacter(world.campaignId, a1.userId, "deleted-sheet");
assert.deepEqual(fieldedSheets(world.campaign()).map(sheet => sheet.id), [a1.id, b1.id, companion.id]);
campaigns.updateGameSettings(world.campaignId, { multiCharacter: "all_active" });
assert.equal(fieldedSheets(world.campaign()).length, 5);
console.log("ok: selection, initiative actor, reactions, ownership, AI distinction and single-character compatibility");
const params = { params: Promise.resolve({ campaignId: world.campaignId }) };
const request = body => new Request("http://localhost/api/test", { method: "POST", headers: { "Content-Type": "application/json" }, body: JSON.stringify(body) });
const switchRoute = await world.route("campaigns/[campaignId]/sheet/switch");
world.signIn(world.owner);
assert.equal((await switchRoute.POST(request({ characterId: a2.id }), params)).status, 200);
assert.equal(sheets.getSheetForUser(world.campaignId, a1.userId).id, a2.id);
assert.equal((await switchRoute.POST(request({ characterId: b1.id }), params)).status, 404);
assert.equal((await switchRoute.POST(request({ characterId: companion.id }), params)).status, 404);
assert.equal(all().length, 5);
assert.deepEqual(all().map(s => [s.id, s.userId]), [a1, a2, b1, b2, companion].map(s => [s.id, s.userId]));
const join = await world.route("campaigns/join");
world.signIn({ id: b1.userId });
campaigns.setMemberActiveCharacter(world.campaignId, b1.userId, b2.id);
const rejoined = await join.POST(request({ inviteCode: world.campaign().inviteCode }));
assert.equal(rejoined.status, 200);
assert.equal(sheets.getSheetForUser(world.campaignId, b1.userId).id, b2.id);
assert.equal(all().length, 5);
console.log("ok: switch permissions, ownership preservation and room reconnect retain both sheets");
const usage = await world.route("campaigns/[campaignId]/sheet/usage");
world.patch(b1.id, { resources: { secondWind: { max: 1, used: 0 } } });
world.patch(b2.id, { resources: { secondWind: { max: 1, used: 0 } } });
assert.equal((await usage.POST(request({ characterId: b1.id, resources: { secondWind: 1 } }), params)).status, 200);
assert.equal(world.sheet(b1.id).resources.secondWind.used, 1);
assert.equal(world.sheet(b2.id).resources.secondWind.used, 0);
assert.equal((await usage.POST(request({ characterId: a1.id, resources: { secondWind: 1 } }), params)).status, 404);
assert.equal((await usage.POST(request({ characterId: "missing", resources: { secondWind: 1 } }), params)).status, 404);
console.log("ok: sheet resource updates target the named owned sheet without affecting siblings");
// Human adjudication keeps this integration test entirely model-free.
campaigns.setDmMode(world.campaignId, "human", world.owner.id);
const actions = await world.route("campaigns/[campaignId]/actions");
campaigns.setFloor(world.campaignId, { mode: "open" });
const action = await actions.POST(request({ content: "I inspect the door.", kind: "do", characterId: b1.id }), params);
assert.equal(action.status, 202, JSON.stringify(await action.clone().json()));
assert.equal(listRecentMessages(world.campaignId, 1)[0].characterId, b1.id);
assert.equal((await actions.POST(request({ content: "I act.", characterId: a1.id }), params)).status, 404);
console.log("ok: explicit action attribution uses the owned character, independent of current selection");
world.say("dm", "The fight begins.");
await world.beginFight([{ monster: "goblin", count: 1 }], { heroFaces: { [a1.id]: 20, [a2.id]: 19, [b1.id]: 18, [b2.id]: 17, [companion.id]: 16 } });
const fight = world.encounter();
const pcs = fight.order.filter(entry => entry.kind === "pc");
assert.equal(pcs.length, 5);
assert.equal(new Set(pcs.map(entry => entry.characterId)).size, 5);
for (const hero of [a1, a2, b1, b2]) assert.equal(pcs.find(entry => entry.characterId === hero.id).userId, hero.userId);
const { publicEncounter } = await import("../src/lib/db/encounter-view.ts");
const projected = publicEncounter(fight, world.enemies(), { enemyNumbers: true });
assert.equal(projected.acting.id, a1.id);
assert.equal(initiativeCharacter(all(), a1.userId, projected.acting.id).id, a1.id);
assert.equal(initiativeCharacter(all(), a1.userId, { ...projected, turn: undefined }.acting.id).id, a1.id);
const { endOwnTurn } = await import("../src/lib/dm/encounter-tools.ts");
assert.equal(endOwnTurn(world.campaignId, a1.userId), true);
assert.equal(endOwnTurn(world.campaignId, a2.userId), true);
for (const hero of [b1, b2]) {
  const current = world.encounter(); assert.equal(current.order[current.turnIndex].characterId, hero.id);
  campaigns.setFloor(world.campaignId, { mode: "initiative", userIds: [hero.userId], currentName: hero.name });
  const map = buildPlayerMapView(world.campaignId, hero.userId);
  assert.ok(map); assert.equal(map.tokens.find(token => token.id === map.myTokenId).refId, hero.id);
  assert.equal(new Set(map.tokens.filter(token => token.kind === "pc").map(token => token.refId)).size, 5);
  assert.equal(characterAwaitingPlayer(world.campaignId).id, hero.id);
  const other = hero.id === b1.id ? b2 : b1;
  assert.equal((await actions.POST(request({ content: "I act.", characterId: other.id }), params)).status, 409);
  const allowed = await actions.POST(request({ content: "I take cover.", characterId: hero.id }), params);
  assert.equal(allowed.status, 202, JSON.stringify(await allowed.clone().json()));
  assert.equal(listRecentMessages(world.campaignId, 1)[0].characterId, hero.id);
  assert.equal(endOwnTurn(world.campaignId, hero.userId), true);
}
assert.equal(world.encounter().order.length, fight.order.length);
console.log("ok: independent initiative and tokens, correct human/actor prompts, no entries duplicated by selection");
world.close();
