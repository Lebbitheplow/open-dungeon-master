// Reads the Open5e content pack's items into src/lib/classes/item-tags.json:
// what each one is (a potion, a wand, a torch, arrows; scripts/lib/
// item-tag-rules.mjs), and the SRD potions the pack keeps as one row with a
// table of kinds (Healing's four, Giant Strength's giants, Resistance's ten
// damage types), each kind with the number its table gives. The engines read
// these by the English name or the slug an item carries (src/lib/srd/
// item-tags.ts), wherever they run, a server with no pack included.
//
// Like the magic-item generator, the OUTPUT IS COMMITTED and loaded at
// runtime. Run by hand when the content pack changes:
//
//   node scripts/generate-item-tags.mjs          # write the file
//   node scripts/generate-item-tags.mjs --check  # fail if stale
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import Database from "better-sqlite3-multiple-ciphers";
import { tagsOfPackItem } from "./lib/item-tag-rules.mjs";
import { ADDED, RETAGGED } from "./lib/item-tag-corrections.mjs";
import { nameBase } from "./lib/name-base.mjs";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const contentDb = join(root, "data", "content", "open5e.sqlite");
const outPath = join(root, "src", "lib", "classes", "item-tags.json");

if (!existsSync(contentDb)) {
  console.error(`content DB not found at ${contentDb}; cannot generate.`);
  process.exit(1);
}

const db = new Database(contentDb, { readonly: true });
// The SRD's documents first, so a name two documents file is read as the
// SRD's row.
const rows = db
  .prepare(
    `SELECT name, slug, kind, category, data_json, document_slug IN ('wotc-srd', 'srd-2014') AS srd FROM items
     ORDER BY CASE WHEN document_slug IN ('wotc-srd', 'srd-2014') THEN 0 ELSE 1 END, name, slug`,
  )
  .all();
db.close();

// Another document's weapon or armor is swung or worn as the SRD one it is
// built on (scripts/lib/name-base.mjs), which the engines read off the row.
const items = rows.map((row) => {
  const tags = RETAGGED[row.name.toLowerCase()] ?? tagsOfPackItem(row.name, row.kind, row.category);
  const base = !row.srd && (row.kind === "weapon" || row.kind === "armor") ? nameBase(row.name, row.kind) : null;
  return base ? [row.name, row.slug, tags, base] : [row.name, row.slug, tags];
});

// ---- the SRD potions' kinds, from their own tables ----

// A markdown table's body rows, as trimmed cells.
function tableRows(desc) {
  return desc
    .split("\n")
    .filter((line) => line.trim().startsWith("|") && !/^\|[\s|:-]+\|$/.test(line.trim()))
    .slice(1)
    .map((line) => line.split("|").slice(1, -1).map((cell) => cell.trim()));
}
const title = (words) => words.replace(/\b\p{L}/gu, (letter) => letter.toUpperCase());

const SRD_POTIONS = {
  // | Healing | Common | 2d4 + 2 |, | Greater healing | ... |
  "potion-of-healing": (cells) => [[`Potion of ${title(cells[0])}`, { heals: cells[2].replace(/\s+/g, "") }]],
  // | Frost/stone giant | 23 | Rare |: one kind for each giant named.
  "potion-of-giant-strength": (cells) =>
    cells[0].replace(/\s*giant$/i, "").split("/").map((giant) => [`Potion of ${title(giant)} Giant Strength`, { strength: Number(cells[1]) }]),
  // | 3 | Fire |
  "potion-of-resistance": (cells) => [[`Potion of ${title(cells[1])} Resistance`, { resists: cells[1].toLowerCase() }]],
};
const kinds = [];
for (const [slug, read] of Object.entries(SRD_POTIONS)) {
  const row = rows.find((entry) => entry.slug === slug);
  if (!row) {
    console.error(`the pack has no ${slug}; cannot read its table.`);
    process.exit(1);
  }
  const tags = items.find(([, itemSlug]) => itemSlug === slug)[2];
  for (const cells of tableRows(JSON.parse(row.data_json).desc ?? "")) {
    for (const [name, effect] of read(cells)) {
      kinds.push([name, tags, effect]);
    }
  }
}

const generated = {
  _note: "GENERATED by scripts/generate-item-tags.mjs from the Open5e content DB. Do not edit by hand; re-run the script instead.",
  // [name, slug, tags] for each pack row, and the SRD weapon or armor a
  // mundane row of another document is built on.
  items,
  // [name, tags] for each thing the SRD names that the pack has no row for.
  added: ADDED.map((entry) => [entry.name, entry.tags]),
  // [name, tags, effect] for each kind of an SRD potion with a table.
  potions: kinds,
};
const serialized = `${JSON.stringify(generated)}\n`;

if (process.argv.includes("--check")) {
  // Compare on content, not line endings (a Windows checkout's CRLF copy).
  const current = existsSync(outPath) ? readFileSync(outPath, "utf8").replace(/\r\n/g, "\n") : "";
  if (current !== serialized) {
    console.error("item-tags.json is stale; re-run node scripts/generate-item-tags.mjs");
    process.exit(1);
  }
  console.log(`item-tags.json is current (${items.length} items, ${kinds.length} potion kinds).`);
} else {
  writeFileSync(outPath, serialized);
  console.log(`Wrote ${items.length} items and ${kinds.length} potion kinds to src/lib/classes/item-tags.json`);
}
